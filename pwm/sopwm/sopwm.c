/* Schedule tables in DMA-accessible GSRAM.
 * The linker must have a "ramgs0" section mapped to GS0 (or any GS RAM). */
#pragma DATA_SECTION(sopwm_sched, "ramgs0")
SOPWM_CycleCmp_t sopwm_sched[3][2][SOPWM_N_CARR_MAX];

float    sopwm_f_fund_hz       = 1000.0f;
uint16_t sopwm_n_carr          = SOPWM_N_CARR_DEFAULT;
uint16_t sopwm_mid_slot_a      = SOPWM_N_CARR_DEFAULT / 2U;
uint16_t sopwm_phase_b_offset  = 33U;
uint16_t sopwm_phase_c_offset  = 17U;

volatile uint16_t sopwm_sched_active = 0U;  /* buffer index in use by DMA   */
volatile uint16_t sopwm_fund_tick    = 0U;  /* flag: new fundamental started */

/* Debug observables — watch these in CCS to diagnose startup */
volatile uint16_t sopwm_init_done  = 0U;  /* set to 1 after InitSchedule completes */
volatile uint16_t sopwm_lut_n_base = 0U;  /* n_base returned by GetAngles (expect 3 for N=7) */
volatile uint16_t sopwm_build_count = 0U; /* increments each BuildSchedule call */

static volatile uint16_t sopwm_swap_pending = 0U;
uint16_t                 sopwm_cycle_idx    = 0U;
static uint16_t          sopwm_sched_next   = 1U;

static float sopwm_cycle_span_deg = 360.0f / (float)SOPWM_N_CARR_DEFAULT;

uint16_t SOPWM_SetFundamentalHz(float f_fund)
{
    uint16_t n_new;
    uint16_t n_min;
    uint16_t n_max;
    float    span_deg;
    uint16_t changed;

    if (f_fund < SOPWM_F_FUND_MIN_HZ) {
        f_fund = SOPWM_F_FUND_MIN_HZ;
    } else if (f_fund > SOPWM_F_FUND_MAX_HZ) {
        f_fund = SOPWM_F_FUND_MAX_HZ;
    }

    n_min = (uint16_t)(SOPWM_F_CARR_HZ / SOPWM_F_FUND_MAX_HZ + 0.5f);
    n_max = (uint16_t)(SOPWM_F_CARR_HZ / SOPWM_F_FUND_MIN_HZ + 0.5f);
    n_new = (uint16_t)(SOPWM_F_CARR_HZ / f_fund + 0.5f);
    if (n_new < n_min) {
        n_new = n_min;
    } else if (n_new > n_max) {
        n_new = n_max;
    }

    changed = (n_new != sopwm_n_carr) ? 1U : 0U;

    sopwm_f_fund_hz      = f_fund;
    sopwm_n_carr         = n_new;
    span_deg             = 360.0f / (float)n_new;
    sopwm_cycle_span_deg = span_deg;
    /* Slot whose span contains 180° (toggle counts computed in closure). */
    sopwm_mid_slot_a     = (uint16_t)(180.0f / span_deg);
    if (sopwm_mid_slot_a >= n_new) {
        sopwm_mid_slot_a = n_new - 1U;
    }
    /* B[k]=A[(k+off_b)%N] lags A by 120°; C lags by 240° (integer round) */
    sopwm_phase_b_offset = (uint16_t)(((uint32_t)n_new * 2U) + 1U) / 3U;
    sopwm_phase_c_offset = (uint16_t)(((uint32_t)n_new) + 1U) / 3U;
    sopwm_cycle_idx      = 0U;

    return changed;
}

void SOPWM_ReconfigDma(uint32_t dma0Base, uint32_t dma1Base, uint32_t dma2Base)
{
    const uint32_t bases[3] = { dma0Base, dma1Base, dma2Base };
    uint16_t       i;
    uint32_t       wrap_bursts;

    /* Wrap counts bursts (not 16-bit words). Two fundamentals per wrap. */
    wrap_bursts = (uint32_t)sopwm_n_carr * 2U;

    for (i = 0U; i < 3U; i++) {
        /*
         * Soft-reset clears burst/transfer counters. Required when n_carr
         * changes (f_fund change); shadow-only configTransfer is not enough.
         */
        DMA_triggerSoftReset(bases[i]);
        DMA_configTransfer(bases[i], (uint32_t)sopwm_n_carr, 1, -2);
        /* Match SysConfig/board.c: src wrap step 0, dest wrap disabled */
        DMA_configWrap(bases[i], wrap_bursts, 0, 65535U, 0);
        DMA_enableTrigger(bases[i]);
    }
}

void SOPWM_ConfigPhaseCPolarity(uint32_t epwm2Base)
{
    /*
     * Rotated phase C is inverted vs the desired A+240 deg leg voltage.
     * SysConfig sets EPWM2 FED Active Low; leave untouched when scope is OK.
     */
    (void)epwm2Base;
}

void SOPWM_ConfigPhaseBPolarity(uint32_t epwm4Base)
{
    /*
     * B[k]=A[(k+off_b)%n], off_b=(2*n+1)/3 → 120 deg lag without leg inversion.
     * RED Active Low (phase A / manual SysConfig on EPWM4) flips B ~180 deg vs C;
     * n_carr=100 @ 500 Hz then looks reversed while n_carr=50 can look OK.
     * C keeps FED Active Low on EPWM2 only.
     */
    EALLOW;
    EPWM_setDeadBandDelayPolarity(epwm4Base, EPWM_DB_RED,
                                  EPWM_DB_POLARITY_ACTIVE_HIGH);
    EPWM_setDeadBandDelayPolarity(epwm4Base, EPWM_DB_FED,
                                  EPWM_DB_POLARITY_ACTIVE_HIGH);
    EDIS;
}

/*
 * sopwm_bin_lut
 *
 * Map quarter-wave angles into carrier slots for phase A (no symmetry yet).
 */
static void sopwm_bin_lut(
        const float      *global_deg,
        uint16_t          total,
        uint16_t          tbprd,
        SOPWM_CycleCmp_t *tbl)
{
    uint16_t i, slot, counts;
    float    local_ang;

    for (i = 0U; i < sopwm_n_carr; i++) {
        tbl[i].cmpa = SOPWM_CMP_OFF;
        tbl[i].cmpb = SOPWM_CMP_OFF;
    }

    for (i = 0U; i < total; i++) {
        slot = (uint16_t)(global_deg[i] / sopwm_cycle_span_deg);
        if (slot >= sopwm_n_carr) slot = sopwm_n_carr - 1U;

        local_ang = global_deg[i] - (float)slot * sopwm_cycle_span_deg;
        counts    = (uint16_t)((local_ang / sopwm_cycle_span_deg)
                               * (float)tbprd + 0.5f);
        if (counts >= tbprd) counts = tbprd - 1U;

        if (tbl[slot].cmpa == SOPWM_CMP_OFF) {
            tbl[slot].cmpa = counts;
        } else if (tbl[slot].cmpb == SOPWM_CMP_OFF) {
            if (counts < tbl[slot].cmpa) {
                tbl[slot].cmpb = tbl[slot].cmpa;
                tbl[slot].cmpa = counts;
            } else {
                tbl[slot].cmpb = counts;
            }
        }
    }
}

/*
 * sopwm_insert_counts — place one compare event in a carrier slot (cmpa < cmpb).
 */
static void sopwm_insert_counts(
        SOPWM_CycleCmp_t *slot,
        uint16_t          counts)
{
    if (slot->cmpa == SOPWM_CMP_OFF) {
        slot->cmpa = counts;
    } else if (slot->cmpb == SOPWM_CMP_OFF) {
        if (counts < slot->cmpa) {
            slot->cmpb = slot->cmpa;
            slot->cmpa = counts;
        } else {
            slot->cmpb = counts;
        }
    }
}

/*
 * sopwm_force_halfwave_toggle
 *
 * Insert the half-wave symmetry toggle at exactly 180° electrical.
 * n/2 slot leading edge is only 180° when n_carr is even; odd n_carr
 * (e.g. 63 @ 800 Hz) needs a non-zero count within the mid slot.
 */
static void sopwm_force_halfwave_toggle(
        SOPWM_CycleCmp_t *tbl,
        uint16_t          tbprd)
{
    const float mid_deg = 180.0f;
    uint16_t    mid_slot;
    uint16_t    mid_counts;
    float       local;

    mid_slot = (uint16_t)(mid_deg / sopwm_cycle_span_deg);
    if (mid_slot >= sopwm_n_carr) {
        mid_slot = sopwm_n_carr - 1U;
    }

    local = mid_deg - (float)mid_slot * sopwm_cycle_span_deg;
    mid_counts = (uint16_t)((local / sopwm_cycle_span_deg) * (float)tbprd + 0.5f);
    if (mid_counts >= tbprd) {
        mid_counts = tbprd - 1U;
    }

    if (mid_counts == 0U) {
        if (tbl[mid_slot].cmpa == SOPWM_CMP_OFF) {
            tbl[mid_slot].cmpa = 0U;
        } else if (tbl[mid_slot].cmpa != 0U && tbl[mid_slot].cmpb == SOPWM_CMP_OFF) {
            tbl[mid_slot].cmpb = tbl[mid_slot].cmpa;
            tbl[mid_slot].cmpa = 0U;
        } else if (tbl[mid_slot].cmpb == SOPWM_CMP_OFF) {
            tbl[mid_slot].cmpb = 0U;
        }
    } else {
        sopwm_insert_counts(&tbl[mid_slot], mid_counts);
    }
}

/*
 * sopwm_frame_closure
 *
 * Force a toggle at exactly 180° electrical, then close 360° = 0° when
 * the toggle count is odd.
 */
static void sopwm_frame_closure(
        SOPWM_CycleCmp_t *tbl,
        uint16_t          tbprd)
{
    uint16_t i, n_toggles;

    sopwm_force_halfwave_toggle(tbl, tbprd);

    n_toggles = 0U;
    for (i = 0U; i < sopwm_n_carr; i++) {
        if (tbl[i].cmpa != SOPWM_CMP_OFF) {
            n_toggles++;
        }
        if (tbl[i].cmpb != SOPWM_CMP_OFF) {
            n_toggles++;
        }
    }

    if ((n_toggles & 1U) != 0U) {
        /*
         * Close the odd toggle at the PERIOD END (~360 deg), never at slot 0
         * counter 0.  A toggle at slot 0 / counter 0 sits exactly on the
         * fundamental boundary and races the one-time SW force used to
         * re-anchor the AQ latch on a param change (sopwm_apply_param_change):
         * the force and the counter-0 toggle would fight and can invert the
         * leg.  Placing it at the last usable slot keeps slot 0 event-free so
         * the re-anchor is deterministic, while still giving an even toggle
         * count (the leg returns to its LOW start each fundamental).
         */
        uint16_t k = sopwm_n_carr;
        while (k-- > 0U) {
            if ((tbl[k].cmpb == SOPWM_CMP_OFF) &&
                (tbl[k].cmpa != SOPWM_CMP_OFF) &&
                (tbl[k].cmpa < (tbprd - 1U))) {
                tbl[k].cmpb = tbprd - 1U;
                break;
            }
            if (tbl[k].cmpa == SOPWM_CMP_OFF) {
                tbl[k].cmpa = tbprd - 1U;
                break;
            }
        }
    }
}

/*
 * sopwm_copy_rotated_phase
 *
 * Phase B/C schedules are slot-rotated copies of the closed phase-A table.
 */
static void sopwm_copy_rotated_phase(
        uint16_t          dst_ph,
        uint16_t          src_ph,
        uint16_t          slot_offset,
        uint16_t          buf_idx)
{
    const SOPWM_CycleCmp_t *src = sopwm_sched[src_ph][buf_idx];
    SOPWM_CycleCmp_t       *dst = sopwm_sched[dst_ph][buf_idx];
    uint16_t                k;

    for (k = 0U; k < sopwm_n_carr; k++) {
        dst[k] = src[(k + slot_offset) % sopwm_n_carr];
    }
}

void SOPWM_InitSchedule(float m, uint16_t N, uint16_t tbprd)
{
    /*
     * Always populate BOTH buffers explicitly.  Do not restore
     * sopwm_sched_next — after runtime swaps it may be 0, which would
     * build the same buffer twice and leave the other stale.
     */
    sopwm_sched_active  = 0U;
    sopwm_sched_next    = 0U;
    sopwm_swap_pending  = 0U;
    sopwm_cycle_idx     = 0U;

    SOPWM_BuildSchedule(m, N, tbprd);

    sopwm_sched_next = 1U;
    SOPWM_BuildSchedule(m, N, tbprd);

    sopwm_sched_next = 1U;   /* inactive buffer for next BuildSchedule */
    sopwm_init_done  = 1U;
}

void SOPWM_BuildSchedule(float m, uint16_t N, uint16_t tbprd)
{
    float    base_deg[7];
    float    all_angles[28];   /* 4 * 7 max */
    uint16_t n_base, total, i;

    /* Fetch N base angles (degrees, Q1 only) from LUT */
    n_base = SOPWM_GetAngles(m, N, base_deg);
    sopwm_lut_n_base = n_base;   /* DEBUG: should be N/2 rounded up (3 for N=7) */
    if (n_base == 0U) return;

    sopwm_build_count++;          /* DEBUG: should reach 2 after InitSchedule */

    total = 4U * n_base;

    /* Quarter-wave expansion → all 4N global angles for phase A */
    for (i = 0U; i < n_base; i++)
        all_angles[i]             = base_deg[i];               /* Q1 */
    for (i = 0U; i < n_base; i++)
        all_angles[n_base + i]    = 180.0f
                                    - base_deg[n_base - 1U - i]; /* Q2 */
    for (i = 0U; i < n_base; i++)
        all_angles[2U*n_base + i] = 180.0f + base_deg[i];       /* Q3 */
    for (i = 0U; i < n_base; i++)
        all_angles[3U*n_base + i] = 360.0f
                                    - base_deg[n_base - 1U - i]; /* Q4 */

    /* Phase A: LUT → slots → 180° closure + 360°=0° if odd toggle count.
     * B/C: rotated copies of closed A (mid toggles land at 300° / 60°). */
    sopwm_bin_lut(all_angles, total, tbprd,
                  sopwm_sched[0][sopwm_sched_next]);
    sopwm_frame_closure(sopwm_sched[0][sopwm_sched_next], tbprd);
    sopwm_copy_rotated_phase(1U, 0U, sopwm_phase_b_offset, sopwm_sched_next);
    sopwm_copy_rotated_phase(2U, 0U, sopwm_phase_c_offset, sopwm_sched_next);
}

void SOPWM_CommitSchedule(void)
{
    /* Arm the newly built buffer; swap happens at next fundamental boundary */
    sopwm_swap_pending = 1U;
}

void SOPWM_schedISR(void)
{
    /* Advance the carrier-cycle counter */
    sopwm_cycle_idx++;

    if (sopwm_cycle_idx >= sopwm_n_carr) {
        sopwm_cycle_idx = 0U;

        /* If main loop has committed a new schedule, swap the buffers now.
         * The DMA source-begin address must be updated separately by the
         * caller after checking sopwm_sched_active (see DMA instructions). */
        if (sopwm_swap_pending) {
            sopwm_sched_active ^= 1U;
            sopwm_sched_next   ^= 1U;
            sopwm_swap_pending  = 0U;
        }

        /* Signal main loop to rebuild the next buffer */
        sopwm_fund_tick = 1U;
    }
}
